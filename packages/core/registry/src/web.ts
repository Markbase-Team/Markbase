import { enabledFeatures, loadFeatures, type LoadedFeature } from "./load";
import type { FeatureRuntime } from "./runtime";

// What the Next build needs from the manifests. Build-time only — it reaches
// the filesystem through `loadFeatures`.

/**
 * Workspace packages that are not features and ship in every release.
 *
 * `transpilePackages` needs every workspace package the app imports, and that
 * is a larger set than "the features": the kernel is always there and cannot be
 * left out, so there is nothing for a manifest to decide. Listing it here keeps
 * the generated half honestly generated instead of inventing manifests for
 * packages no release would ever drop.
 */
export const KERNEL_PACKAGES = [
  "@markbase/agent",
  "@markbase/browser-agent",
  "@markbase/flows",
  "@markbase/llm",
  "@markbase/node",
  "@markbase/protocol",
  "@markbase/ui",
  "@markbase/vault",
] as const;

/**
 * `transpilePackages` for this build: the kernel, plus every enabled feature's
 * package. Sorted, so regenerating on another machine produces no diff.
 *
 * Next transpiles a listed package only if something imports it, so naming one
 * the app never reaches is a no-op rather than a cost.
 */
export function transpilePackages(
  features: LoadedFeature[] = enabledFeatures(loadFeatures())
): string[] {
  const featurePkgs = features
    .map((f) => f.manifest.pkg)
    .filter((p): p is string => p != null);
  return [...KERNEL_PACKAGES, ...featurePkgs].sort();
}

/**
 * Path prefixes belonging to features this build left out.
 *
 * Computed as "all minus enabled" rather than read off the disabled manifests
 * at request time, because the app has no manifests to read. The proxy 404s
 * anything under one of these.
 */
export function disabledRoutesEnvValue(
  all: LoadedFeature[] = loadFeatures(),
  enabled: LoadedFeature[] = enabledFeatures(all)
): string {
  const on = new Set(enabled.map((f) => f.manifest.id));
  return JSON.stringify(
    all.filter((f) => !on.has(f.manifest.id)).flatMap((f) => f.manifest.routes)
  );
}

/**
 * What the build inlines for the app to read at request time.
 *
 * Next's `env` substitutes this string at build time, so the app never reaches
 * for the `packages/` tree — which does not exist in a deployed serverless
 * bundle. Only what the app actually needs crosses over: the id and the sidebar
 * entries, not the whole manifest.
 */
export function featuresEnvValue(
  features: LoadedFeature[] = enabledFeatures(loadFeatures())
): string {
  const runtime: FeatureRuntime[] = features.map((f) => ({
    id: f.manifest.id,
    sidebar: f.manifest.sidebar,
  }));
  return JSON.stringify(runtime);
}

/**
 * The generated slot map: feature id → its sidebar section, as a module.
 *
 * Generated rather than committed because it must contain only what this build
 * ships. A committed map that imported every feature would pull a dropped
 * feature's code back into the bundle, which is the one property R4 exists to
 * provide — and the build would still succeed, so nothing would say so.
 *
 * Only packaged features can contribute: there is no subpath to import from a
 * feature whose code still sits in the app.
 */
export function sidebarSlotsModule(
  features: LoadedFeature[] = enabledFeatures(loadFeatures())
): string {
  const contributing = features
    .filter((f) => f.manifest.pkg && f.manifest.contributes.sidebar)
    .sort((a, b) => a.manifest.id.localeCompare(b.manifest.id));

  const imports = contributing
    .map(
      (f, i) =>
        `import Slot${i} from "${f.manifest.pkg}${f.manifest.contributes.sidebar!.slice(1)}";`
    )
    .join("\n");
  const entries = contributing
    .map((f, i) => `  ${JSON.stringify(f.manifest.id)}: Slot${i},`)
    .join("\n");

  const providing = features
    .filter((f) => f.manifest.pkg && f.manifest.contributes.providers?.length)
    .sort((a, b) => a.manifest.id.localeCompare(b.manifest.id))
    .flatMap((f) =>
      f.manifest.contributes.providers!.map((sub) => `${f.manifest.pkg}${sub.slice(1)}`)
    );
  const providerImports = providing
    .map((spec, i) => `import Provider${i} from "${spec}";`)
    .join("\n");
  const providerList = providing.map((_, i) => `  Provider${i},`).join("\n");

  const routeDecls = features
    .filter((f) => f.manifest.pkg && f.manifest.contributes.routes)
    .sort((a, b) => a.manifest.id.localeCompare(b.manifest.id))
    .map(
      (f) =>
        `import type {} from "${f.manifest.pkg}${f.manifest.contributes.routes!.slice(1)}";`
    )
    .join("\n");

  return `// GENERATED by apps/web/scripts/gen-feature-slots.ts — do not edit.
// Regenerated on every build from the feature manifests, so it contains only
// what this build ships.
import type { ComponentType, ReactNode } from "react";
import type { SidebarSlotMap } from "@markbase/ui/sidebar-slot";
${routeDecls}
${imports}
${providerImports}

export const FEATURE_SIDEBAR_SLOTS: SidebarSlotMap = {
${entries}
};

/** Wrapped outermost-first around the whole surface. */
export const FEATURE_PROVIDERS: ComponentType<{ children: ReactNode }>[] = [
${providerList}
];
`;
}

/**
 * The route group the generated stubs live in.
 *
 * A group, so the URL is unchanged, and one group per place in the app tree
 * that has a layout to inherit: `dashboard/(features)/…` sits under the
 * dashboard layout, `(features)/…` under the root one. Both directories are
 * wholly generated and gitignored, and the generator empties them before it
 * writes, so a build with fewer features leaves no route behind.
 */
export const APP_ROUTE_GROUP = "(features)";

/** Where the generator writes, relative to `apps/web/src/app`. All of them. */
export const APP_ROUTE_GROUP_DIRS = [APP_ROUTE_GROUP, `dashboard/${APP_ROUTE_GROUP}`];

/** One generated route file: where it goes under `app/`, and what it says. */
export interface AppRouteStub {
  file: string;
  source: string;
}

const GENERATED_HEADER =
  "// GENERATED by apps/web/scripts/gen-feature-slots.ts — do not edit.\n" +
  "// Written from the feature manifests on every build, so this file exists\n" +
  "// only in a build that ships the feature it names.\n";

/**
 * The route files this build's features contribute, as stubs for the app.
 *
 * A route stub re-exports the package module's handlers and carries the
 * segment config itself, because Next reads `runtime` and `maxDuration` off
 * the route file's own source and would not see them through a re-export. A
 * page or layout stub renders the package's component with the shell's
 * `PageHost`, which is the one thing a page needs that only the shell has.
 *
 * Only packaged features can contribute, as with the sidebar: the stub
 * imports a subpath of the package.
 */
export function appRouteStubs(
  features: LoadedFeature[] = enabledFeatures(loadFeatures())
): AppRouteStub[] {
  const stubs: AppRouteStub[] = [];
  const owners = new Map<string, string>();

  const contributing = [...features]
    .filter((f) => f.manifest.pkg && f.manifest.contributes.app?.length)
    .sort((a, b) => a.manifest.id.localeCompare(b.manifest.id));

  for (const f of contributing) {
    const pkg = f.manifest.pkg!;
    for (const raw of f.manifest.contributes.app!) {
      const entry = typeof raw === "string" ? { path: raw } : raw;
      const path = entry.path;
      // Two features claiming one file is a build that serves one of them
      // and says nothing. Next refuses the duplicate too, but by then the
      // message names two generated files and neither feature.
      const prior = owners.get(path);
      if (prior) {
        throw new Error(
          `${f.file}: app route "${path}" is already contributed by feature "${prior}"`
        );
      }
      owners.set(path, f.manifest.id);

      const kind = path.slice(path.lastIndexOf("/") + 1) as "route" | "page" | "layout";
      const specifier = `${pkg}/app/${path}`;
      const group = path.startsWith("dashboard/")
        ? `dashboard/${APP_ROUTE_GROUP}/${path.slice("dashboard/".length)}`
        : `${APP_ROUTE_GROUP}/${path}`;

      if (kind === "route") {
        const config = [
          `export const runtime = "nodejs";`,
          entry.maxDuration != null ? `export const maxDuration = ${entry.maxDuration};` : "",
          entry.dynamic ? `export const dynamic = ${JSON.stringify(entry.dynamic)};` : "",
        ]
          .filter(Boolean)
          .join("\n");
        stubs.push({
          file: `${group}.ts`,
          source:
            GENERATED_HEADER +
            `// ${pkg} serves /${path.slice(0, -"/route".length)}.\n` +
            `export * from ${JSON.stringify(specifier)};\n` +
            `${config}\n`,
        });
        continue;
      }

      const config = [
        entry.dynamic ? `export const dynamic = ${JSON.stringify(entry.dynamic)};` : "",
        entry.title ? `export const metadata = { title: ${JSON.stringify(entry.title)} };` : "",
      ]
        .filter(Boolean)
        .join("\n");
      const name = kind === "layout" ? "FeatureLayout" : "FeaturePage";
      stubs.push({
        file: `${group}.tsx`,
        source:
          GENERATED_HEADER +
          `// ${pkg} renders /${path.slice(0, -(kind.length + 1))}.\n` +
          `import type { ComponentProps } from "react";\n` +
          `import Contributed from ${JSON.stringify(specifier)};\n` +
          `import { pageHost } from "@/lib/page-host";\n` +
          (config ? `${config}\n` : "") +
          `\n` +
          `// The host is the shell's, not the route's: Next passes params and\n` +
          `// children, this adds the one prop only the shell can supply.\n` +
          `type Props = Omit<ComponentProps<typeof Contributed>, "host">;\n` +
          `\n` +
          `export default function ${name}(props: Props) {\n` +
          `  return <Contributed {...props} host={pageHost} />;\n` +
          `}\n`,
      });
    }
  }

  return stubs;
}

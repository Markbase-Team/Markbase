import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { buildSync } from "esbuild";
import { repoRoot } from "@markbase/registry";

// Writes src/generated/editor-card.ts: the document editor that runs inside an
// AI app's card (packages/features/docs/src/ui/card/editor-card.ts), bundled
// into one script, with the editor's stylesheet. The card page carries them
// inline — a card may load nothing from anywhere — so they are strings the
// MCP server puts in the page (@markbase/shared/docs/apps/editor-app). Run
// before `next dev`, `next build`, `tsc` and the tests, like gen-docs.ts.
const root = repoRoot();
const out = join(root, "apps/web/src/generated/editor-card.ts");

const bundle = buildSync({
  entryPoints: [join(root, "packages/features/docs/src/ui/card/editor-card.ts")],
  bundle: true,
  format: "iife",
  platform: "browser",
  target: "es2020",
  minify: true,
  write: false,
  legalComments: "none",
  // One page, no outside requests: nothing may be left to load at run time.
  splitting: false,
});
// Inline in a <script>: nothing in it may close the element.
const js = bundle.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
const css = readFileSync(join(root, "packages/features/docs/src/ui/tiptap.css"), "utf8");

mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `// Generated by scripts/gen-editor-card.ts. Do not edit.\nexport const EDITOR_CARD_JS = ${JSON.stringify(js)};\nexport const EDITOR_CARD_CSS = ${JSON.stringify(css)};\n`
);
console.log(`editor card: ${(js.length / 1024).toFixed(0)} KiB of script, ${(css.length / 1024).toFixed(0)} KiB of style`);

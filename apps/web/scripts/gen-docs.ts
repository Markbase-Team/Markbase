import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { repoRoot } from "@markbase/registry";

// Writes src/generated/docs-pages.ts from apps/web/content/docs/*.md, so the
// docs pages are plain markdown files a contributor edits, and the server never
// reads the disk at request time (its working directory differs between the
// dev server, Vercel and the Docker image). Run before `next dev`, `next build`,
// `tsc` and the tests, like gen-feature-slots.ts.
const web = join(repoRoot(), "apps/web");
const dir = join(web, "content/docs");
const pages: Record<string, string> = {};
for (const file of readdirSync(dir).filter((f) => f.endsWith(".md")).sort()) {
  pages[file.replace(/\.md$/, "")] = readFileSync(join(dir, file), "utf8");
}
const out = join(web, "src/generated/docs-pages.ts");
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  "// GENERATED by scripts/gen-docs.ts from content/docs/*.md. Edit those, not this.\n" +
    `export const DOCS_MARKDOWN: Record<string, string> = ${JSON.stringify(pages, null, 2)};\n`
);
console.log(`wrote ${out} (${Object.keys(pages).length} pages)`);

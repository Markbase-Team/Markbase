import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { repoRoot } from "@markbase/registry";

// Writes src/generated/docs-pages.ts from apps/web/content/docs/*.md, and
// src/generated/blog-posts.ts from content/blog/*.md, so the docs pages and
// the blog posts are plain markdown files a contributor edits, and the server never
// reads the disk at request time (its working directory differs between the
// dev server, Vercel and the Docker image). Run before `next dev`, `next build`,
// `tsc` and the tests, like gen-feature-slots.ts.
const web = join(repoRoot(), "apps/web");

/** Every `.md` file in a content directory, by file name without the extension. */
function readMarkdown(dir: string): Record<string, string> {
  const pages: Record<string, string> = {};
  for (const file of readdirSync(dir).filter((f) => f.endsWith(".md")).sort()) {
    pages[file.replace(/\.md$/, "")] = readFileSync(join(dir, file), "utf8");
  }
  return pages;
}

/** Write one generated module holding a content directory's markdown. */
function generate(content: string, module: string, constant: string): void {
  const pages = readMarkdown(join(web, "content", content));
  const out = join(web, "src/generated", module);
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(
    out,
    `// GENERATED by scripts/gen-docs.ts from content/${content}/*.md. Edit those, not this.\n` +
      `export const ${constant}: Record<string, string> = ${JSON.stringify(pages, null, 2)};\n`
  );
  console.log(`wrote ${out} (${Object.keys(pages).length} pages)`);
}

generate("docs", "docs-pages.ts", "DOCS_MARKDOWN");
generate("blog", "blog-posts.ts", "BLOG_MARKDOWN");
